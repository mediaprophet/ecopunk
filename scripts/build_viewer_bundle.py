#!/usr/bin/env python3
"""
Builds viewer/data/catalog_bundle.js and data/catalog/qualia_mcp_verification.json
so the EcoPunk 3D Viewer has immediate zero-latency access to all 6 realistic
sectors, 105 East Coast Flora species, 64 East Coast Fauna species, and QualiaDB
substrate verification metrics whether opened via HTTP or file://.
"""

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

def main():
    sectors_path = ROOT / "data" / "geospatial" / "sectors_terrain.json"
    flora_path = ROOT / "data" / "catalog" / "flora_100.json"
    fauna_path = ROOT / "data" / "catalog" / "fauna_64.json"

    with open(sectors_path, "r", encoding="utf-8") as f:
        sectors_data = json.load(f)
    with open(flora_path, "r", encoding="utf-8") as f:
        flora_data = json.load(f)
    with open(fauna_path, "r", encoding="utf-8") as f:
        fauna_data = json.load(f)

    qualia_verification = {
        "daemon": "qualia-core-db-mcp",
        "graph_quin_count": 7634,
        "ontologies_ingested": [
            {"file": "data/ontologies/east_coast_flora_100.ttl", "quins": 4568, "species": len(flora_data.get("species", []))},
            {"file": "data/ontologies/east_coast_fauna_64.ttl", "quins": 2744, "species": len(fauna_data.get("species", []))},
            {"file": "data/ontologies/subsurface_strata.ttl", "quins": 103},
            {"file": "data/ontologies/biocultural_stewardship.ttl", "quins": 57},
            {"file": "data/ontologies/heliophysics_climate.ttl", "quins": 42},
            {"file": "data/ontologies/east_coast_taxa.ttl", "quins": 120}
        ],
        "deontic_governance": {
            "tool": "deontic_govern",
            "policy_mode": "Prioritize",
            "permits_execution": True,
            "licence": "SocialPermissiveCommons",
            "perpetual_royalties_prohibited": True
        },
        "computational_geometry": {
            "tool": "computational_geometry",
            "op": "delaunay_2",
            "triangle_count": 8,
            "triangles": [[0,1,5],[1,0,6],[1,2,5],[2,1,6],[2,3,5],[3,2,6],[3,4,5],[4,3,6]]
        },
        "substrates": {
            "q42": "assets/terrain/east_coast_strata.q42",
            "m64": "assets/terrain/talbingo_catchment.m64",
            "h10d": "assets/terrain/talbingo_heightfield.10d",
            "lut_16kb": "assets/terrain/constituent_lut_16kb.bin"
        }
    }

    ver_path = ROOT / "data" / "catalog" / "qualia_mcp_verification.json"
    with open(ver_path, "w", encoding="utf-8") as f:
        json.dump(qualia_verification, f, indent=2)
    print(f"[OK] Wrote {ver_path}")

    bundle = {
        "sectors": sectors_data.get("sectors", []),
        "flora": flora_data.get("species", []),
        "fauna": fauna_data.get("species", []),
        "quinCount": 7634,
        "qualia_verification": qualia_verification
    }

    out_dir = ROOT / "viewer" / "data"
    out_dir.mkdir(parents=True, exist_ok=True)
    bundle_path = out_dir / "catalog_bundle.js"
    js_content = "// Auto-generated by scripts/build_viewer_bundle.py\nwindow.ECOPUNK_MASTER_DATA = " + json.dumps(bundle, separators=(",", ":")) + ";\n"
    with open(bundle_path, "w", encoding="utf-8") as f:
        f.write(js_content)
    print(f"[OK] Wrote {bundle_path} ({bundle_path.stat().st_size:,} bytes) — {len(bundle['flora'])} flora, {len(bundle['fauna'])} fauna, {len(bundle['sectors'])} sectors, {bundle['quinCount']} quins")

if __name__ == "__main__":
    main()
