def rgb_to_jakob_hanika(rgb: List[float]) -> List[float]:
    """
    Approximate polynomial spectral upsampling coefficients [c0, c1, c2]
    following Jakob & Hanika (2019) smooth reflectance parametrization for
    bounded sRGB albedo in [0.02, 0.98].
    """
    r, g, b = [max(0.02, min(0.98, float(x))) for x in rgb]
    lum = 0.2126 * r + 0.7152 * g + 0.0722 * b
    c0 = round((b - g) * 2.45, 4)
    c1 = round((g - r) * 1.85, 4)
    c2 = round(math.log(lum / (1.0 - lum)) * 0.65, 4)
    return [c0, c1, c2]


