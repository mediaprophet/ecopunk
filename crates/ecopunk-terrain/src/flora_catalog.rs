fn build_flora_record_from_spec(
    idx: usize,
    id: &str,
    scientific_name: &str,
    common_name: &str,
    indigenous_name: &str,
    custodial_country: &str,
    family: &str,
    genus: &str,
    order: &str,
    growth_form: &str,
    bark_type: &str,
    height_max_m: f32,
    height_typ_m: f32,
    elev_min_m: i32,
    elev_max_m: i32,
    bark_rgb: [f32; 3],
    foliage_rgb: [f32; 3],
    flower_rgb: [f32; 3],
    sectors: &[&str],
) -> Value {
    // 1. Run qualia-sim LeafVascularSkeleton biophysics
    let mut leaf_profile = match family {
        "Myrtaceae" | "Proteaceae" | "Casuarinaceae" => LeafEconomicsProfile::eucalyptus_sclerophyll(),
        "Poaceae" | "Cyperaceae" | "Juncaceae" | "Restionaceae" => LeafEconomicsProfile::monocot_grass(),
        _ => LeafEconomicsProfile::herbaceous_broadleaf(),
    };
    let leaf_len_m = match growth_form {
        "tree_fern" | "palm_rosette" | "cycad_rosette" => 1.65,
        "ground_fern" | "tussock_grass" | "reed_sedge" | "mat_rush_lomandra" | "aquatic_submerged" => 0.55,
        "moss_bryophyte" | "fungi_cluster" | "alpine_cushion" => 0.04,
        _ => 0.14,
    };
    leaf_profile.leaf_length_m = leaf_len_m;
    leaf_profile.leaf_width_m = leaf_len_m * 0.24;
    let leaf_skeleton = LeafVascularSkeleton::new(leaf_profile, 1.35);

    // 2. Run qualia-sim FloraArchetypeConfig & MetamerPlantGraph
    let archetype = match growth_form {
        "tussock_grass" | "reed_sedge" | "mat_rush_lomandra" | "spear_grass" => FloraArchetypeConfig::tussock_grass(),
        "climbing_vine" => FloraArchetypeConfig::climbing_vine(),
        "alpine_cushion" => FloraArchetypeConfig::succulent(),
        "wildflower_herb" | "orchid_rock" | "kangaroo_paw" | "gymea_lily" | "ground_fern" => FloraArchetypeConfig::culinary_herb(),
        _ => FloraArchetypeConfig::woody_tree(),
    };
    let phenology = ThermalPhenology::default();
    let mut metamer_graph = MetamerPlantGraph::new(phenology);
    metamer_graph.update_thermal_time(24.0, 11.0, 45.0);
    metamer_graph.solve_growth_cycle(1.0, 0.82);

    let dbh_max_m = (height_max_m * 0.038).clamp(0.02, 2.8);
    let crown_spread_m = (height_typ_m * 0.62).clamp(0.18, 26.0);
    let is_10d_twin = id == "corymbia_aparrerinja";

    json!({
        "index": idx,
        "id": id,
        "scientific_name": scientific_name,
        "common_name": common_name,
        "indigenous_name": indigenous_name,
        "custodial_country": custodial_country,
        "taxonomy": {
            "kingdom": if growth_form == "fungi_cluster" { "Fungi" } else { "Plantae" },
            "family": family,
            "genus": genus,
            "order": order,
        },
        "distribution": {
            "elevation_min_m": elev_min_m,
            "elevation_max_m": elev_max_m,
            "sectors": sectors,
            "bioregions": ["Australian Alps (AA)", "South Eastern Highlands (SEH)", "Sydney Basin (SB)", "South Eastern Queensland (SEQ)"],
        },
        "allometry": {
            "growth_form": growth_form,
            "height_max_m": height_max_m,
            "height_typical_m": height_typ_m,
            "dbh_max_m": (dbh_max_m * 100.0).round() / 100.0,
            "crown_spread_m": (crown_spread_m * 100.0).round() / 100.0,
            "lignification": archetype.lignification,
            "branch_insertion_angle_deg": leaf_profile.branching_angle_rad.to_degrees().round(),
            "phyllotaxis_divergence_deg": 137.50776,
            "fspm_metamer_count": metamer_graph.count,
        },
        "bark_and_foliage": {
            "bark_type": bark_type,
            "bark_albedo_rgb": bark_rgb,
            "foliage_albedo_rgb": foliage_rgb,
            "flower_accent_rgb": flower_rgb,
            "sggx_transmittance": 0.24,
            "leaf_venation_nodes": leaf_skeleton.edge_count,
            "leaf_midrib_rigidity_pa": leaf_profile.tissue_elastic_modulus_mpa * 1.0e6,
            "leaf_mass_per_area_kg_m2": leaf_profile.lma_g_m2 * 1.0e-3,
            "vein_density_mm_per_mm2": leaf_profile.vein_density_mm_per_mm2,
        },
        "digital_twin_10d": if is_10d_twin {
            json!({
                "enabled": true,
                "container_format": "10d_v1_surf1_impo1",
                "manifest_path": "entities/taxa/corymbia-aparrerinja/entity.json",
                "vibe_script": "entities/taxa/corymbia-aparrerinja/corymbia-aparrerinja.vibe",
                "mesh_chunks": [
                    "assets/models/corymbia-aparrerinja/10d/trunk.10d",
                    "assets/models/corymbia-aparrerinja/10d/bark.10d",
                    "assets/models/corymbia-aparrerinja/10d/foliage.10d",
                    "assets/models/corymbia-aparrerinja/10d/buds.10d",
                    "assets/models/corymbia-aparrerinja/10d/flowers.10d",
                    "assets/models/corymbia-aparrerinja/10d/capsules.10d",
                    "assets/models/corymbia-aparrerinja/10d/taproot.10d",
                    "assets/models/corymbia-aparrerinja/10d/lateral_roots.10d"
                ]
            })
        } else {
            json!({ "enabled": false })
        }
    })
}

/// Enriches the existing 105 East Coast flora records with `qualia-sim` leaf biophysics
/// and appends 200 new Australian flora species (45 `EXTRA_200_FLORA` + 155 `EXTRA_FLORA_TUPLES` = 200),
/// producing the authoritative 305-species Flora Catalog.
pub fn compile_305_flora_catalog(existing_json: &Value) -> Value {
    let mut species_out: Vec<Value> = Vec::with_capacity(305);

    if let Some(arr) = existing_json.get("species").and_then(|v| v.as_array()) {
        for (_i, item) in arr.iter().take(105).enumerate() {
            let mut enriched = item.clone();
            let fam = enriched
                .pointer("/taxonomy/family")
                .and_then(|v| v.as_str())
                .unwrap_or("Myrtaceae");
            let leaf_profile = match fam {
                "Myrtaceae" | "Proteaceae" | "Casuarinaceae" => LeafEconomicsProfile::eucalyptus_sclerophyll(),
                "Poaceae" | "Cyperaceae" | "Juncaceae" => LeafEconomicsProfile::monocot_grass(),
                _ => LeafEconomicsProfile::herbaceous_broadleaf(),
            };
            let skel = LeafVascularSkeleton::new(leaf_profile, 1.35);
            if let Some(bf) = enriched.get_mut("bark_and_foliage").and_then(|v| v.as_object_mut()) {
                bf.insert("leaf_venation_nodes".to_string(), json!(skel.edge_count));
                bf.insert("leaf_midrib_rigidity_pa".to_string(), json!(leaf_profile.tissue_elastic_modulus_mpa * 1.0e6));
                bf.insert("leaf_mass_per_area_kg_m2".to_string(), json!(leaf_profile.lma_g_m2 * 1.0e-3));
                bf.insert("vein_density_mm_per_mm2".to_string(), json!(leaf_profile.vein_density_mm_per_mm2));
            }
            species_out.push(enriched);
        }
    }

    let mut next_idx = species_out.len() + 1;
    for s in EXTRA_200_FLORA {
        if species_out.len() >= 305 {
            break;
        }
        species_out.push(build_flora_record_from_spec(
            next_idx,
            s.id,
            s.scientific_name,
            s.common_name,
            s.indigenous_name,
            s.custodial_country,
            s.family,
            s.genus,
            s.order,
            s.growth_form,
            s.bark_type,
            s.height_max_m,
            s.height_typ_m,
            s.elev_min_m,
            s.elev_max_m,
            s.bark_rgb,
            s.foliage_rgb,
            s.flower_rgb,
            s.sectors,
        ));
        next_idx += 1;
    }

    for t in EXTRA_FLORA_TUPLES {
        if species_out.len() >= 305 {
            break;
        }
        species_out.push(build_flora_record_from_spec(
            next_idx,
            t.0, t.1, t.2, t.3, t.4, t.5, t.6, t.7, t.8, t.9,
            t.10, t.11, t.12, t.13, t.14, t.15, t.16, t.17,
        ));
        next_idx += 1;
    }

    json!({
        "dataset_id": "ecopunk-east-coast-flora-305-v2",
        "title": "East Coast Australia 305-Species Multi-Stratum Flora & Leaf Biophysics Catalog",
        "compiler": "ecopunk-terrain::flora_catalog (Rust + qualia-sim LeafVascularSkeleton + MetamerPlantGraph + VibeScript)",
        "total_species": species_out.len(),
        "species": species_out,
    })
}

